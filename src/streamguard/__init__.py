"""StreamGuard - local-first anomaly and drift monitoring for simulated telemetry.

Everything in this package operates on *simulated* data generated by
:mod:`streamguard.simulator`. Nothing is connected to a real system, and no
metric produced by this project should be read as a claim about real-world
detection performance.

See ``MODEL_CARD.md`` and ``LIMITATIONS.md`` at the repository root.
"""

from __future__ import annotations

__all__ = [
    "FEATURE_COLUMNS",
    "FEATURE_LABELS",
    "FEATURE_UNITS",
    "SIMULATED_DATA_LABEL",
    "Alert",
    "AlertStore",
    "AppConfig",
    "Dataset",
    "DetectorConfig",
    "DriftConfig",
    "SimulatorConfig",
    "__version__",
    "load_config",
]

__version__ = "0.1.0"

SIMULATED_DATA_LABEL = "SIMULATED"


def __getattr__(name: str) -> object:  # pragma: no cover - trivial lazy re-export
    """Lazily re-export the public API without importing heavy deps eagerly."""
    from streamguard import alerts, config, simulator

    _exports = {
        "FEATURE_COLUMNS": simulator.FEATURE_COLUMNS,
        "FEATURE_LABELS": simulator.FEATURE_LABELS,
        "FEATURE_UNITS": simulator.FEATURE_UNITS,
        "Alert": alerts.Alert,
        "AlertStore": alerts.AlertStore,
        "AppConfig": config.AppConfig,
        "Dataset": simulator.Dataset,
        "DetectorConfig": config.DetectorConfig,
        "DriftConfig": config.DriftConfig,
        "SimulatorConfig": config.SimulatorConfig,
        "load_config": config.load_config,
    }
    try:
        return _exports[name]
    except KeyError as exc:  # pragma: no cover - standard module behaviour
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}") from exc
